import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Optional display-name overrides: slug -> display name
const NAME_OVERRIDES = {}

const LOWERCASE_WORDS = new Set(['of', 'the', 'a', 'an', 'and', 'in', 'on'])
const CATEGORY_ORDER = ['Slots', 'Fishing', 'Others']
const IMAGE_EXTS = new Set(['.webp', '.png', '.jpg', '.jpeg'])

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const GAMES_DIR = path.join(ROOT, 'public', 'games')
const OUTPUT_FILE = path.join(ROOT, 'src', 'data', 'games.js')

function formatCategory(folder) {
  return folder
    .split('-')
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(' ')
}

function formatName(slug) {
  if (Object.prototype.hasOwnProperty.call(NAME_OVERRIDES, slug)) {
    return NAME_OVERRIDES[slug]
  }
  return slug
    .split('-')
    .filter(Boolean)
    .map((word, index) => {
      const lower = word.toLowerCase()
      if (index > 0 && LOWERCASE_WORDS.has(lower)) {
        return lower
      }
      return lower.charAt(0).toUpperCase() + lower.slice(1)
    })
    .join(' ')
}

function compareCategories(a, b) {
  const ai = CATEGORY_ORDER.indexOf(a)
  const bi = CATEGORY_ORDER.indexOf(b)
  if (ai !== -1 && bi !== -1) return ai - bi
  if (ai !== -1) return -1
  if (bi !== -1) return 1
  return a.localeCompare(b)
}

if (!fs.existsSync(GAMES_DIR) || !fs.statSync(GAMES_DIR).isDirectory()) {
  console.error(`Error: ${GAMES_DIR} does not exist. Add game posters under public/games/<category>/.`)
  process.exit(1)
}

const folders = fs
  .readdirSync(GAMES_DIR, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)

const byCategory = new Map()

for (const folder of folders) {
  const folderPath = path.join(GAMES_DIR, folder)
  const files = fs
    .readdirSync(folderPath, { withFileTypes: true })
    .filter((entry) => entry.isFile() && IMAGE_EXTS.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)

  if (files.length === 0) continue

  const label = formatCategory(folder)
  const list = byCategory.get(label) || []

  for (const filename of files) {
    const ext = path.extname(filename)
    const slug = path.basename(filename, ext)
    list.push({
      id: slug,
      name: formatName(slug),
      cat: label,
      image: `/games/${folder}/${filename}`,
    })
  }

  byCategory.set(label, list)
}

const sortedCategories = [...byCategory.keys()].sort(compareCategories)
const games = []

for (const cat of sortedCategories) {
  const items = byCategory.get(cat)
  items.sort((a, b) => a.name.localeCompare(b.name))
  games.push(...items)
}

if (games.length === 0) {
  console.error(`Error: No game images (.webp, .png, .jpg, .jpeg) found in ${GAMES_DIR}.`)
  process.exit(1)
}

const categoriesExport = ['All', ...sortedCategories]
const lines = [
  '// AUTO-GENERATED by scripts/generate-games.mjs. Do not edit by hand.',
  `export const CATEGORIES = ${JSON.stringify(categoriesExport)}`,
  '',
  'export const GAMES = [',
  ...games.map(
    (g) =>
      `  { id: ${JSON.stringify(g.id)}, name: ${JSON.stringify(g.name)}, cat: ${JSON.stringify(g.cat)}, image: ${JSON.stringify(g.image)} },`
  ),
  ']',
  '',
]

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true })
fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8')

const summaryParts = sortedCategories.map((cat) => `${cat}: ${byCategory.get(cat).length}`)
console.log(`${summaryParts.join(', ')} (${games.length} games)`)
